        public static string Headline(IntelOffer offer)
            => offer.Index==0?"전해 들은 짧은 이야기":Stories[offer.Story].Headline[offer.ClaimedPositive?1:0];
        public static string Body(IntelOffer offer)
        {
            var story=Stories[offer.Story];int side=offer.ClaimedPositive?1:0;
            if(offer.Index==0)return story.Vague[side]+"\n\n누가, 언제 움직이는지는 빠져 있다. 다른 정황과 맞춰 볼 필요가 있다.";
            if(offer.Index==1)return story.Headline[side]+".\n\n다음 거래일 진행될 사건으로 취재됐다. 구체적인 업체명, 규모와 계약 조건은 이 자료에 담겨 있지 않다.";
            return story.Detail[side];
        }
        public static string Evidence(IntelOffer offer)
            => offer.Index==0?"단일 제보 · 교차 확인 부족":offer.Index==1?"복수 제보 · 사건 일정 취재":"일정·참여 명단·조건 교차 취재";
        public static string FollowUp(ClueRecord record)
        {
            var offer=record.Offer;
            return (offer.ActualPositive==offer.ClaimedPositive?"취재 내용과 일치\n":"취재 내용과 불일치\n")+
                Stories[offer.Story].Headline[offer.ActualPositive?1:0]+".";
        }
